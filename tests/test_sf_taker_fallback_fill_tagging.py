"""v1.4.163 — SF taker-fallback fill tagging.

Bug context: snapshot ``v1.4.157-260520-213540-prod.okx.ton.usdt.perp``
contained 3 fills at 17:15:00.757-758 that were the actual closing
fills of soft-flatten episode SF#11167. Those fills were generated by
the taker-fallback path in ``app/bot.py:2369``:

    self._client.market_close(self._settings.symbol)

That call bypasses ``ExecutionEngine.place_order`` entirely — no row
ever gets inserted into the local ``orders`` SQLite table for the
market-close order. When the resulting fills arrive at fill
ingestion, ``order_metadata_for_fill_ingest`` returns the all-None
dict (parent absent), and the fills end up with
``soft_flatten_event_id=None`` despite being SF-attributable.

Visible symptoms in production:
  - The SF chart markers' tooltip says "0 fills" for the episode
    (v1.4.162 marker-rendering fix surfaces the marker but the LEFT
    JOIN over ``fills`` returns 0 because the fills are untagged).
  - The fills-history UI doesn't tag those rows as SF.
  - ``live_stats._soft_flatten_attribution_block`` undercounts.
  - Postmortem joins on ``soft_flatten_event_id`` miss the closing
    fills entirely.

Fix: in ``fill_ingestion.ingest_hl_fill_raw``, when
``order_metadata_for_fill_ingest`` returns no SF tag AND
``parent_order_exists`` confirms the parent isn't in the local DB
AND ``state.soft_flatten_event_id`` is currently set, stamp the fill
with the active SF event id. The ``parent_order_exists`` check
distinguishes "taker-fallback case (NO parent)" from "pre-SF order
whose cancel raced a fill (parent present but untagged)" — only the
former should be stamped.

These tests cover the fix's correctness across the cases.
"""

from __future__ import annotations

import os
import tempfile
